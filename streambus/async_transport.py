from typing import Protocol, runtime_checkable


@runtime_checkable
class AsyncEventTransport(Protocol):
    async def publish(self, stream: str, data: dict) -> None: ...
    async def read(self, stream: str, group: str, consumer: str, batch_size: int, block_ms: int) -> list[tuple[str, dict]]: ...
    async def ack(self, stream: str, group: str, msg_id: str) -> None: ...
    async def ensure_group(self, stream: str, group: str) -> None: ...
    async def reconnect(self) -> None: ...
